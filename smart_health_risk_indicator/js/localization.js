class LocalizationController {
    constructor() {
        this.supportedLocales = ["en", "hi", "te", "ta"];
        this.currentLocale = localStorage.getItem("shri_locale") || "en";
        if (!this.supportedLocales.includes(this.currentLocale)) {
            this.currentLocale = "en";
        }
    }

    setLocale(lang) {
        if (!this.supportedLocales.includes(lang)) lang = "en";
        this.currentLocale = lang;
        localStorage.setItem("shri_locale", lang);
        document.documentElement.lang = lang;
        this.applyTranslations();

        // Dispatch custom event for charts or dynamic sub-modules
        window.dispatchEvent(new CustomEvent("shri_locale_changed", { detail: { locale: lang } }));
    }

    t(key, fallback = "") {
        const dict = SHRI_I18N[this.currentLocale] || SHRI_I18N.en;
        if (dict && dict[key] !== undefined) return dict[key];
        if (SHRI_I18N.en && SHRI_I18N.en[key] !== undefined) return SHRI_I18N.en[key];
        return fallback || key;
    }


    getPatientName(patId, fallbackName = "") {
        const lang = this.currentLocale;
        if (PATIENT_METADATA_I18N[patId] && PATIENT_METADATA_I18N[patId][lang]) {
            return PATIENT_METADATA_I18N[patId][lang].name;
        }
        for (const pid in PATIENT_METADATA_I18N) {
            const entry = PATIENT_METADATA_I18N[pid];
            if (entry.en && entry.en.name.toLowerCase() === (fallbackName || "").toLowerCase()) {
                return (entry[lang] && entry[lang].name) || fallbackName;
            }
        }
        return fallbackName;
    }

    getPatientGender(gender) {
        const lang = this.currentLocale;
        if (GENDER_I18N[gender] && GENDER_I18N[gender][lang]) {
            return GENDER_I18N[gender][lang];
        }
        return gender;
    }

    getPatientConcern(patId, fallbackConcern = "") {
        const lang = this.currentLocale;
        if (PATIENT_METADATA_I18N[patId] && PATIENT_METADATA_I18N[patId][lang]) {
            return PATIENT_METADATA_I18N[patId][lang].concern;
        }
        return fallbackConcern;
    }

    getPatientDiagnosis(patId, fallbackDiagnosis = "") {
        const lang = this.currentLocale;
        if (PATIENT_METADATA_I18N[patId] && PATIENT_METADATA_I18N[patId][lang]) {
            return PATIENT_METADATA_I18N[patId][lang].diagnosis;
        }
        return fallbackDiagnosis;
    }

    getPatientNotes(patId, fallbackNotes = "") {
        const lang = this.currentLocale;
        if (PATIENT_METADATA_I18N[patId] && PATIENT_METADATA_I18N[patId][lang]) {
            return PATIENT_METADATA_I18N[patId][lang].notes;
        }
        return fallbackNotes;
    }

    getRiskTierText(tier) {
        const clean = (tier || "LOW").toUpperCase().replace(" RISK", "").trim();
        const lang = this.currentLocale;
        if (RISK_TIER_I18N[clean] && RISK_TIER_I18N[clean][lang]) {
            return RISK_TIER_I18N[clean][lang];
        }
        return tier;
    }

    getClinicianName(name) {
        const lang = this.currentLocale;
        for (const cname in CLINICIAN_METADATA_I18N) {
            if ((name || "").includes(cname) || cname.includes(name || "")) {
                return (CLINICIAN_METADATA_I18N[cname][lang] && CLINICIAN_METADATA_I18N[cname][lang].name) || name;
            }
        }
        return name;
    }

    getClinicianRole(role) {
        const lang = this.currentLocale;
        for (const cname in CLINICIAN_METADATA_I18N) {
            const entry = CLINICIAN_METADATA_I18N[cname];
            if (entry.en && entry.en.role === role) {
                return (entry[lang] && entry[lang].role) || role;
            }
        }
        if (role === "doctor" || role === "Lead Clinician") {
            return this.t("leadClinician", "Lead Clinician & Neuropsychiatrist");
        }
        if (role === "patient" || role === "Adolescent Patient") {
            return this.t("adolescentPatient", "Adolescent Patient");
        }
        return role;
    }

    applyTranslations() {
        const lang = this.currentLocale;
        const dict = SHRI_I18N[lang] || SHRI_I18N.en;
        document.documentElement.lang = lang;

        // 1. Elements with data-i18n attribute
        document.querySelectorAll("[data-i18n]").forEach(el => {
            const key = el.getAttribute("data-i18n");
            if (dict[key]) {
                el.innerText = dict[key];
            } else if (SHRI_I18N.en[key]) {
                el.innerText = SHRI_I18N.en[key];
            }
        });

        // 2. Elements with data-i18n-html attribute (for rich formatted text)
        document.querySelectorAll("[data-i18n-html]").forEach(el => {
            const key = el.getAttribute("data-i18n-html");
            if (dict[key]) {
                el.innerHTML = dict[key];
            } else if (SHRI_I18N.en[key]) {
                el.innerHTML = SHRI_I18N.en[key];
            }
        });

        // 3. Input Placeholders with data-i18n-placeholder
        document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
            const key = el.getAttribute("data-i18n-placeholder");
            if (dict[key]) {
                el.placeholder = dict[key];
            } else if (SHRI_I18N.en[key]) {
                el.placeholder = SHRI_I18N.en[key];
            }
        });

        // 4. Element Titles / Tooltips with data-i18n-title
        document.querySelectorAll("[data-i18n-title]").forEach(el => {
            const key = el.getAttribute("data-i18n-title");
            if (dict[key]) {
                el.title = dict[key];
            }
        });

        // 5. Update All Language Switcher Select Dropdowns across the page
        document.querySelectorAll(".language-switcher-select").forEach(sel => {
            sel.value = lang;
        });
        const headerSel = document.getElementById("language-switcher-select");
        if (headerSel) headerSel.value = lang;
        const authSel = document.getElementById("auth-language-switcher-select");
        if (authSel) authSel.value = lang;

        // 5b. Update Quick Demo Login Buttons
        const docDemoBtn = document.getElementById("demo-doctor-login-btn");
        if (docDemoBtn) {
            docDemoBtn.innerHTML = this.t("quickDemoDoctor");
        }
        const patDemoBtn = document.getElementById("demo-patient-login-btn");
        if (patDemoBtn) {
            patDemoBtn.innerHTML = this.t("quickDemoPatient");
        }

        // 5c. Update Sidebar Profile
        const sideUserName = document.getElementById("sidebar-user-name");
        const sideUserRole = document.getElementById("sidebar-user-role");
        if (typeof currentUser !== "undefined" && currentUser) {
            if (currentUser.role === "doctor") {
                if (sideUserName) sideUserName.innerText = this.getClinicianName(currentUser.name || "Dr. Ramesh S");
                if (sideUserRole) sideUserRole.innerText = this.getClinicianRole(currentUser.title || "Lead Clinician");
            } else {
                if (sideUserName) sideUserName.innerText = this.getPatientName(currentUser.id, currentUser.name || "Aarav Singh");
                if (sideUserRole) sideUserRole.innerText = this.t("adolescentPatient", "Adolescent Patient");
            }
        }

        // 5d. Update Patient Portal Welcome Greeting
        const welcomeGreet = document.getElementById("patient-portal-welcome-name");
        if (welcomeGreet) {
            const patId = (typeof currentUser !== "undefined" && currentUser && currentUser.role === "patient") ? currentUser.id : "PT-1001";
            const rawName = (typeof currentUser !== "undefined" && currentUser && currentUser.role === "patient") ? currentUser.name : "Aarav Singh";
            const locPName = this.getPatientName(patId, rawName);
            welcomeGreet.innerText = `${this.t("greetingHello", "Hello")}, ${locPName}! 👋`;
        }

        // 5e. Update Active Patient Dossier Banner & Dropdown
        if (typeof activePatientId !== "undefined" && activePatientId && typeof patientsDB !== "undefined") {
            const curPat = patientsDB.find(p => p.id === activePatientId);
            if (curPat) {
                const dossierName = document.getElementById("dossier-patient-name");
                const dossierSub = document.getElementById("dossier-patient-sub");
                const yUnit = this.t("yearsUnit", "y");
                const pLabel = this.t("primaryLabel", "Primary");
                if (dossierName) dossierName.innerText = this.getPatientName(curPat.id, curPat.name);
                if (dossierSub) dossierSub.innerText = `${curPat.age}${yUnit} ${this.getPatientGender(curPat.gender)} | ID: ${curPat.id} | ${pLabel}: ${this.getPatientConcern(curPat.id, curPat.primaryConcern)}`;
                
                const dossierDrop = document.getElementById("dossier-patient-dropdown");
                if (dossierDrop) {
                    dossierDrop.innerHTML = "";
                    patientsDB.forEach(p => {
                        const opt = document.createElement("option");
                        opt.value = p.id;
                        opt.innerText = `${this.getPatientName(p.id, p.name)} (${p.id} - ${this.getRiskTierText(p.riskTier)})`;
                        if (p.id === curPat.id) opt.selected = true;
                        dossierDrop.appendChild(opt);
                    });
                }
            }
        }

        // 6. Dynamic Views Update
        const regView = document.getElementById("doctor-registry-view");
        const dosView = document.getElementById("doctor-patient-detail-view");
        const valView = document.getElementById("doctor-validation-view");
        const dsView = document.getElementById("doctor-datasets-view");
        const patView = document.getElementById("patient-portal-view");

        const pageTitle = document.getElementById("page-main-title");
        const pageSub = document.getElementById("page-subtitle");

        if (pageTitle && pageSub) {
            if (regView && regView.style.display !== "none") {
                pageTitle.innerText = this.t("patientRegistry", "Patient Registry Dashboard");
                pageSub.innerText = this.t("patientRegistrySub", "Enrolled Adolescent Patients & Continuous Risk Monitoring");
            } else if (dosView && dosView.style.display !== "none") {
                pageTitle.innerText = this.t("patientDossier", "Patient Clinical Dossier");
                pageSub.innerText = this.t("patientDossierSub", "Comprehensive Multimodal Phenotyping, Permutation XAI & Clinical Action Plans");
            } else if (valView && valView.style.display !== "none") {
                pageTitle.innerText = this.t("benchmarkTitle", "Multi-Hospital Pilot Benchmark & Clinical Validation");
                pageSub.innerText = this.t("benchmarkSubtitle", "Multi-Center Cohort Validation (N = 10,000) across Metropolitan Medical Center, Apollo Children's & NIMHANS");
            } else if (dsView && dsView.style.display !== "none") {
                pageTitle.innerText = this.t("datasetsTitle", "Clinical Diagnostic Questionnaires & Psychometric Datasets");
                pageSub.innerText = this.t("datasetsSubtitle", "AACAP & DSM-5 Validated Screening Batteries, 10-Cohort Registry, and Doctor-Psychologist Clinical Protocols");
            }
        }

        if (typeof renderRegistryStats === "function") {
            renderRegistryStats();
        }
        if (typeof renderPatientCards === "function") {
            renderPatientCards();
        }
        if (typeof renderCohortDatasetTable === "function") {
            renderCohortDatasetTable();
        }
        const audioTbody = document.getElementById("audio-history-tbody");
        if (typeof renderAudioHistoryTable === "function" && audioTbody && audioTbody.offsetParent !== null) {
            renderAudioHistoryTable();
        }
    }
}

// Global singleton instance
window.shriI18n = new LocalizationController();

// Convenience shorthand
function t(key, fallback = "") {
    return window.shriI18n ? window.shriI18n.t(key, fallback) : (fallback || key);
}
